class _Capture(TypedDict):
    bytes: int
    sample: bytes
    truncated: bool
    read_error: bool
    drained: bool
    nonempty: bool


def _new_capture() -> _Capture:
    return {
        "bytes": 0,
        "sample": b"",
        "truncated": False,
        "read_error": False,
        "drained": False,
        "nonempty": False,
    }


def _drain(stream: BinaryIO, capture: _Capture,
           on_line: Callable[[bytes], None] | None = None) -> None:
    """Drain a process stream while retaining only a bounded private sample."""
    sample = bytearray()
    buffered = bytearray()
    try:
        while True:
            chunk = stream.read(65536)
            if not chunk:
                break
            capture["nonempty"] = True
            capture["bytes"] += len(chunk)
            remaining = MAX_CAPTURE_BYTES - len(sample)
            if remaining > 0:
                sample.extend(chunk[:remaining])
            if len(chunk) > remaining:
                capture["truncated"] = True
            if on_line is not None:
                buffered.extend(chunk)
                while True:
                    try:
                        end = buffered.index(10)
                    except ValueError:
                        break
                    line = bytes(buffered[:end + 1])
                    del buffered[:end + 1]
                    if len(line) > MAX_LINE_BYTES:
                        on_line(b"")
                    else:
                        on_line(line)
                if len(buffered) > MAX_LINE_BYTES:
                    buffered.clear()
                    on_line(b"")
    except (OSError, ValueError):
        capture["read_error"] = True
    finally:
        if on_line is not None and buffered:
            on_line(b"" if len(buffered) > MAX_LINE_BYTES else bytes(buffered))
        capture["sample"] = bytes(sample)
        capture["drained"] = True


def _safe_environment(docker_config: Path) -> dict[str, str]:
    """Construct the minimal process environment needed by the fixture."""
    value = {
        key: os.environ[key]
        for key in SAFE_ENV_KEYS
        if key in os.environ
    }
    # Docker reads this directory, never the protected Codex login home.  The
    # caller validates that the directory is an empty disposable fixture.
    value["DOCKER_CONFIG"] = str(docker_config)
    return value


def _safe_error_code(error: BaseException) -> str:
    if isinstance(error, ValueError):
        return "input-validation"
    if isinstance(error, subprocess.TimeoutExpired):
        return "process-timeout"
    if isinstance(error, PermissionError):
        return "process-access-denied"
    if isinstance(error, FileNotFoundError):
        return "executable-not-found"
    if isinstance(error, subprocess.SubprocessError):
        return "process-subprocess-error"
    if isinstance(error, OSError):
        return "process-os-error"
    return "process-error"


def _command_ok(value: Mapping[str, Any]) -> bool:
    return bool(
        value.get("process_started") is True
        and value.get("exit_code") == 0
        and value.get("timed_out") is False
        and value.get("stdin_write_failed") is False
        and value.get("stdout_drained") is True
        and value.get("stderr_drained") is True
        and value.get("stdout_read_error") is False
        and value.get("stderr_read_error") is False
    )


def _terminate_process(process: subprocess.Popen[bytes], deadline: float) -> bool:
    if process.poll() is not None:
        return True
    try:
        remaining = max(0.1, deadline - time.monotonic())
        if os.name == "nt":
            subprocess.run(
                ["taskkill", "/PID", str(process.pid), "/T", "/F"],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                check=False, timeout=min(5.0, remaining),
            )
        else:
            process.terminate()
    except (OSError, subprocess.SubprocessError):
        pass
    try:
        process.wait(timeout=max(0.1, deadline - time.monotonic()))
        return True
    except subprocess.TimeoutExpired:
        try:
            process.kill()
        except (OSError, ValueError):
            pass
        try:
            process.wait(timeout=max(0.1, deadline - time.monotonic()))
        except subprocess.TimeoutExpired:
            return False
        return True


def _process_result(value: dict[str, Any], stdout: _Capture,
                    stderr: _Capture, *, timed_out: bool,
                    stdin_write_failed: bool,
                    launch_error: str | None = None) -> dict[str, Any]:
    value.update({
        "process_started": launch_error is None,
        "exit_code": value.get("exit_code"),
        "timed_out": timed_out,
        "stdin_write_failed": stdin_write_failed,
        "stdout_bytes": stdout["bytes"],
        "stderr_bytes": stderr["bytes"],
        "stdout_drained": stdout["drained"],
        "stderr_drained": stderr["drained"],
        "stdout_read_error": stdout["read_error"],
        "stderr_read_error": stderr["read_error"],
        "stdout_truncated": stdout["truncated"],
        "stderr_truncated": stderr["truncated"],
        "stderr_nonempty": stderr["nonempty"],
        "launch_error": launch_error,
    })
    return value


def _run_process(command: list[str], *, env: Mapping[str, str], timeout: int,
                 input_data: bytes | None = None,
                 on_stdout_line: Callable[[bytes], None] | None = None,
                 response_event: threading.Event | None = None,
                 wait_for_response: bool = False) -> tuple[dict[str, Any], bytes]:
    """Run one bounded process and return only safe stream metadata and sample."""
    stdout = _new_capture()
    stderr = _new_capture()
    started = time.monotonic()
    try:
        process = subprocess.Popen(
            command,
            stdin=subprocess.PIPE if input_data is not None else subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=dict(env),
            bufsize=0,
        )
    except (OSError, subprocess.SubprocessError) as error:
        result = _process_result({"exit_code": None}, stdout, stderr,
                                 timed_out=False, stdin_write_failed=False,
                                 launch_error=_safe_error_code(error))
        return result, b""

    assert process.stdout is not None and process.stderr is not None
    stdout_thread = threading.Thread(
        target=_drain, args=(process.stdout, stdout, on_stdout_line),
        name="remote-child-stdout", daemon=True,
    )
    stderr_thread = threading.Thread(
        target=_drain, args=(process.stderr, stderr),
        name="remote-child-stderr", daemon=True,
    )
    stdout_thread.start()
    stderr_thread.start()
    stdin_write_failed = False
    timed_out = False
    deadline = started + timeout
    try:
        if input_data is not None:
            assert process.stdin is not None
            try:
                process.stdin.write(input_data)
                process.stdin.flush()
            except (BrokenPipeError, OSError):
                stdin_write_failed = True
        if wait_for_response and response_event is not None:
            while response_event.is_set() is False and process.poll() is None:
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    timed_out = True
                    break
                response_event.wait(timeout=min(0.05, remaining))
        if process.poll() is None and time.monotonic() >= deadline:
            timed_out = True
        if process.stdin is not None:
            try:
                process.stdin.close()
            except OSError:
                pass
        if timed_out:
            stopped = _terminate_process(process, time.monotonic() + 5)
            if not stopped:
                timed_out = True
        else:
            remaining = deadline - time.monotonic()
            try:
                process.wait(timeout=max(0.1, remaining))
            except subprocess.TimeoutExpired:
                timed_out = True
                _terminate_process(process, time.monotonic() + 5)
    finally:
        if process.stdin is not None:
            try:
                process.stdin.close()
            except OSError:
                pass
    stdout_thread.join(timeout=5)
    stderr_thread.join(timeout=5)
    for stream in (process.stdout, process.stderr):
        try:
            stream.close()
        except (OSError, ValueError):
            pass
    result = _process_result(
        {"exit_code": process.poll()}, stdout, stderr,
        timed_out=timed_out, stdin_write_failed=stdin_write_failed,
    )
    return result, stdout["sample"]


def _docker_command(docker: Path, config: Path, *args: str) -> list[str]:
    return [str(docker), "--config", str(config), *args]


def _container_presence(docker: Path, config: Path, name: str) -> dict[str, Any]:
    try:
        result = subprocess.run(
            _docker_command(
                docker, config, "ps", "-a", "--filter", f"name=^{name}$",
                "--format", "{{.Names}}",
            ),
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            check=False, timeout=5, env=_safe_environment(config),
        )
    except (OSError, subprocess.SubprocessError):
        return {"status": "unavailable", "absent": False}
    if result.returncode != 0:
        return {"status": "unavailable", "absent": False}
    return {
        "status": "available" if not result.stdout.strip() else "occupied",
        "absent": not bool(result.stdout.strip()),
    }


def _container_absent(docker: Path, config: Path, name: str) -> bool:
    """Compatibility predicate; evidence callers use _container_presence."""
    return _container_presence(docker, config, name)["absent"] is True


def _inspect_named_container(docker: Path, config: Path, name: str) -> dict[str, Any]:
    try:
        result = subprocess.run(
            _docker_command(
                docker, config, "inspect", name, "--format",
                "{{.Name}}|{{.State.Status}}|{{.State.ExitCode}}",
            ),
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            check=False, timeout=5, env=_safe_environment(config),
        )
    except (OSError, subprocess.SubprocessError):
        return {"available": False, "owned": False, "status": "unavailable", "exit_code": None}
    fields = result.stdout.decode("ascii", errors="ignore").strip().split("|")
    if result.returncode != 0 or len(fields) != 3:
        return {"available": False, "owned": False, "status": "unavailable", "exit_code": None}
    try:
        exit_code: int | None = int(fields[2])
    except ValueError:
        exit_code = None
    safe_states = {"created", "running", "paused", "restarting", "removing", "exited", "dead"}
    return {
        "available": True,
        "owned": fields[0] == "/" + name,
        "status": fields[1] if fields[1] in safe_states else "unknown",
        "exit_code": exit_code,
    }


def _cleanup_container(docker: Path, config: Path, name: str) -> dict[str, Any]:
    presence = _container_presence(docker, config, name)
    if presence["status"] == "available":
        return {"status": "absent", "verified": True}
    if presence["status"] == "unavailable":
        return {"status": "presence-check-unavailable", "verified": False}
    observation = _inspect_named_container(docker, config, name)
    if observation.get("owned") is not True:
        return {"status": "not-owned-or-unavailable", "verified": False}
    try:
        result = subprocess.run(
            _docker_command(docker, config, "rm", "-f", name),
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            check=False, timeout=5, env=_safe_environment(config),
        )
    except (OSError, subprocess.SubprocessError):
        return {"status": "remove-error", "verified": False}
    absent = _container_absent(docker, config, name)
    return {
        "status": "removed" if result.returncode == 0 else "remove-failed",
        "verified": result.returncode == 0 and absent,
    }


def _initialize_observation() -> dict[str, Any]:
    return {
        "expected_id_responses": 0,
        "initialize_successes": 0,
        "initialize_error_codes": {},
        "malformed_messages": 0,
        "non_json_lines": 0,
        "unexpected_id_responses": 0,
        "notifications_seen": 0,
    }


def _observe_initialize_line(line: bytes, observation: dict[str, Any],
                             event: threading.Event) -> None:
    if not line:
        observation["malformed_messages"] += 1
        return
    try:
        value = json.loads(line.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        observation["non_json_lines"] += 1
        return
    if not isinstance(value, dict):
        observation["malformed_messages"] += 1
        return
    identifier = value.get("id")
    if identifier is None:
        observation["notifications_seen"] += 1
        return
    if type(identifier) not in {int, str}:
        observation["malformed_messages"] += 1
        return
    if identifier != 1:
        observation["unexpected_id_responses"] += 1
        return
    observation["expected_id_responses"] += 1
    error = value.get("error")
    result = value.get("result")
    if isinstance(result, dict) and not isinstance(error, dict):
        observation["initialize_successes"] += 1
    elif isinstance(error, dict) and type(error.get("code")) is int:
        key = str(error["code"])
        codes = observation["initialize_error_codes"]
        codes[key] = codes.get(key, 0) + 1
    else:
        observation["malformed_messages"] += 1
    event.set()


def _rpc_passed(process: Mapping[str, Any], response: Mapping[str, Any],
                cleanup: Mapping[str, Any], telemetry: Mapping[str, Any] | None = None) -> bool:
    telemetry_ok = True if telemetry is None else bool(
        telemetry.get("available") is True
        and telemetry.get("schema_valid") is True
        and telemetry.get("complete") is True
        and telemetry.get("child_exit_code") == 0
        and telemetry.get("mapping_clean") is True
        and telemetry.get("correlated") is True
    )
    return bool(
        _command_ok(process)
        and response.get("expected_id_responses") == 1
        and response.get("initialize_successes") == 1
        and response.get("initialize_error_codes") == {}
        and response.get("malformed_messages") == 0
        and response.get("non_json_lines") == 0
        and response.get("unexpected_id_responses") == 0
        and cleanup.get("verified") is True
        and telemetry_ok
    )


def _canonical_profile(image: str) -> dict[str, Any]:
    return {
        "network_mode": "none",
        "read_only_mounts": [],
        "tmpfs_mounts": ["/tmp"],
        "run_as": "1000:1000",
        "read_write_mounts": list(MOUNT_DESTINATIONS),
        "candidate_env_keys": [
            "HOME", "CODEX_HOME", "PATH", "PYTHONDONTWRITEBYTECODE", "TMPDIR",
        ],
        "image": image,
    }


def _canonical_docker_args(paths: Mapping[str, str], image: str,
                           run_id: str) -> list[str]:
    job = {
        "run_id": run_id,
        "paths": {
            "candidate_dir": paths["candidate_dir"],
            "ephemeral_home": paths["ephemeral_home"],
            "codex_home": paths["codex_home"],
            "temp_dir": paths["temp_dir"],
        },
        "boundary": {"mounts": native_mounts(paths)},
    }
    return expected_docker_args(job, _canonical_profile(image))


def _lifecycle_create_args(docker_args: list[str], image: str) -> list[str]:
    if not docker_args or docker_args[0] != "run":
        raise ValueError("canonical Docker args must start with run")
    image_index = docker_args.index(image)
    return [
        "create", *docker_args[1:image_index], "--entrypoint", "/bin/echo",
        image, LIFECYCLE_MARKER.decode().rstrip("\r\n"),
    ]


def _name_from_args(docker_args: list[str]) -> str:
    try:
        index = docker_args.index("--name")
        name = docker_args[index + 1]
    except (ValueError, IndexError) as error:
        raise ValueError("canonical Docker args have no container name") from error
    if not name or any(char not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_.-" for char in name):
        raise ValueError("diagnostic container name is not safe")
    return name


def _semantic_args(docker_args: list[str]) -> list[str]:
    result = list(docker_args)
    try:
        result[result.index("--name") + 1] = "<unique-container>"
    except (ValueError, IndexError):
        pass
    return result


def _mount_destinations(docker_args: list[str]) -> tuple[str, ...]:
    destinations: list[str] = []
    index = 0
    while index < len(docker_args):
        if docker_args[index] in {"-v", "--volume"} and index + 1 < len(docker_args):
            try:
                _, destination, _ = docker_args[index + 1].rsplit(":", 2)
            except ValueError:
                return ()
            destinations.append(destination)
            index += 2
            continue
        index += 1
    return tuple(destinations)


def _regular_file(path: Path, label: str) -> Path:
    value = path.expanduser().absolute()
    if value.is_symlink() or not value.is_file():
        raise ValueError(f"{label} must be a regular file")
    return value.resolve()


def _directory(path: Path, label: str, *, empty: bool = False) -> Path:
    value = path.expanduser().absolute()
    if value.is_symlink() or not value.is_dir():
        raise ValueError(f"{label} must be a real directory")
    resolved = value.resolve()
    if empty and any(resolved.iterdir()):
        raise ValueError(f"{label} must be an empty disposable directory")
    return resolved


def _prepare_fixture_root(root: Path) -> dict[str, str]:
    value = root.expanduser().absolute()
    if value.exists() or value.is_symlink():
        raise ValueError("fixture root must be a new directory")
    value.mkdir(parents=True)
    paths: dict[str, str] = {}
    for key, dirname in (
        ("candidate_dir", "candidate"),
        ("ephemeral_home", "home"),
        ("codex_home", "codex"),
        ("temp_dir", "temp"),
    ):
        directory = value / dirname
        directory.mkdir()
        paths[key] = str(directory.resolve())
    return paths


def _validate_inputs(*, docker: Path, docker_config: Path, proxy: Path,
                     fixture_root: Path, output: Path, image: str,
                     timeout: int) -> tuple[Path, Path, Path, dict[str, str]]:
    docker = _regular_file(docker, "Docker executable")
    docker_config = _directory(docker_config, "Docker config", empty=True)
    proxy = _regular_file(proxy, "path proxy")
    if image != PROBE_IMAGE:
        raise ValueError("diagnostic requires the pinned remote exec image")
    if not 1 <= timeout <= MAX_TIMEOUT_SECONDS:
        raise ValueError("diagnostic timeout is outside the bounded range")
    output = output.expanduser().absolute()
    if not output.is_absolute() or output.exists() or output.is_symlink():
        raise ValueError("diagnostic output must be a new absolute path")
    paths = _prepare_fixture_root(fixture_root)
    roots = [Path(path).resolve() for path in paths.values()]
    if any(output.resolve(strict=False) == root or output.resolve(strict=False).is_relative_to(root) for root in roots):
        raise ValueError("diagnostic output must not be inside a mounted fixture root")
    return docker, docker_config, proxy, paths


