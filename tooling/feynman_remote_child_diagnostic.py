def _telemetry_summary(path: Path) -> dict[str, Any]:
    base: dict[str, Any] = {
        "available": False,
        "schema_version": None,
        "schema_valid": False,
        "complete": False,
        "requests_seen": 0,
        "requests_forwarded": 0,
        "responses_seen": 0,
        "responses_forwarded": 0,
        "responses_matched": 0,
        "responses_unmatched": 0,
        "pending_request_ids": 0,
        "request_write_failures": 0,
        "request_mapping_rejections": 0,
        "response_mapping_rejections": 0,
        "child_exit_code": None,
        "child_stderr_bytes": 0,
        "child_stderr_nonempty": False,
        "child_stderr_truncated": False,
        "child_stderr_read_error": False,
        "child_stderr_drained": False,
        "mapping_clean": False,
        "correlated": False,
    }
    if path.is_symlink() or not path.is_file():
        return base
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        _validate_startup_telemetry_snapshot(value)
        valid = True
    except (OSError, UnicodeDecodeError, ValueError, json.JSONDecodeError):
        return base
    if not isinstance(value, dict):
        return base
    for key in (
        "requests_seen", "requests_forwarded", "responses_seen", "responses_forwarded",
        "responses_matched", "responses_unmatched", "pending_request_ids",
        "request_write_failures", "request_mapping_rejections", "response_mapping_rejections",
    ):
        if type(value.get(key)) is int and value[key] >= 0:
            base[key] = value[key]
    base.update({
        "available": True,
        "schema_version": value.get("schema_version"),
        "schema_valid": valid,
        "complete": bool(_proxy_telemetry_ready(value)),
        "child_exit_code": value.get("child_exit_code") if type(value.get("child_exit_code")) is int else None,
    })
    for key in ("child_stderr_bytes",):
        if type(value.get(key)) is int and value[key] >= 0:
            base[key] = value[key]
    for key in (
        "child_stderr_nonempty", "child_stderr_truncated",
        "child_stderr_read_error", "child_stderr_drained",
    ):
        if type(value.get(key)) is bool:
            base[key] = value[key]
    base["mapping_clean"] = (
        base["request_mapping_rejections"] == 0
        and base["response_mapping_rejections"] == 0
    )
    base["correlated"] = (
        base["responses_unmatched"] == 0 and base["pending_request_ids"] == 0
    )
    return base


def _run_rpc_variant(*, label: str, docker: Path, config: Path,
                     proxy: Path | None, docker_args: list[str],
                     name: str, telemetry_path: Path | None,
                     timeout: int) -> dict[str, Any]:
    observation = _initialize_observation()
    response_event = threading.Event()
    environment = _safe_environment(config)
    if proxy is None:
        command = _docker_command(docker, config, *docker_args)
        stderr_visibility = "bounded-in-memory"
    else:
        command = [
            sys.executable, "-B", str(proxy), "--docker", str(docker),
            "--telemetry-file", str(telemetry_path), "--", *docker_args,
        ]
        stderr_visibility = "proxy-child-stderr-bounded-counters"
    process, _ = _run_process(
        command, env=environment, timeout=timeout, input_data=INITIALIZE_REQUEST,
        on_stdout_line=lambda line: _observe_initialize_line(line, observation, response_event),
        response_event=response_event, wait_for_response=True,
    )
    cleanup = _cleanup_container(docker, config, name)
    telemetry = _telemetry_summary(telemetry_path) if telemetry_path is not None else None
    passed = _rpc_passed(process, observation, cleanup, telemetry)
    return {
        "label": label,
        "passed": passed,
        "skipped": False,
        "process": process,
        "response": observation,
        "cleanup": cleanup,
        "telemetry": telemetry,
        "stderr_visibility": stderr_visibility,
    }


def run(*, docker: Path, docker_config: Path, proxy: Path,
        fixture_root: Path, output: Path, image: str = PROBE_IMAGE,
        timeout: int = DEFAULT_TIMEOUT_SECONDS) -> dict[str, Any]:
    """Run the bounded direct/proxy differential fixture once."""
    docker, docker_config, proxy, paths = _validate_inputs(
        docker=docker, docker_config=docker_config, proxy=proxy,
        fixture_root=fixture_root, output=output, image=image, timeout=timeout,
    )
    token = uuid.uuid4().hex[:12]
    lifecycle_id = f"remote-child-{token}-lifecycle"
    direct_id = f"remote-child-{token}-direct"
    proxy_id = f"remote-child-{token}-proxy"
    lifecycle_args = _canonical_docker_args(paths, image, lifecycle_id)
    direct_args = _canonical_docker_args(paths, image, direct_id)
    proxy_args = _canonical_docker_args(paths, image, proxy_id)
    lifecycle_name = _name_from_args(lifecycle_args)
    direct_name = _name_from_args(direct_args)
    proxy_name = _name_from_args(proxy_args)
    telemetry_path = output.with_name(output.name + ".proxy-telemetry.json")
    if telemetry_path.exists() or telemetry_path.is_symlink():
        raise ValueError("diagnostic telemetry sidecar must be new")

    stages: dict[str, Any] = {}
    info, _ = _run_process(
        _docker_command(docker, docker_config, "info", "--format", "{{.ServerVersion}}"),
        env=_safe_environment(docker_config), timeout=timeout,
    )
    stages["docker-access"] = _stage_summary(
        info, passed=_command_ok(info) and info["stdout_bytes"] > 0,
    )
    if stages["docker-access"]["passed"]:
        inspect_image, image_sample = _run_process(
            _docker_command(docker, docker_config, "image", "inspect", image, "--format", "{{.Id}}"),
            env=_safe_environment(docker_config), timeout=timeout,
        )
    else:
        inspect_image, image_sample = _not_run_process(), b""
    image_observed = image_sample.strip() == image.encode("ascii")
    stages["image-inspect"] = _stage_summary(
        inspect_image,
        passed=_command_ok(inspect_image) and image_observed,
        image_id_observed=image_observed,
    )

    if stages["docker-access"]["passed"] and stages["image-inspect"]["passed"]:
        name_presence = _container_presence(docker, docker_config, lifecycle_name)
    else:
        name_presence = {"status": "not-run", "absent": False}
    lifecycle_name_available = name_presence["status"] == "available"
    lifecycle_create: dict[str, Any] = {
        "process": _not_run_process(),
        "container": {"available": False, "owned": False, "status": "not-run", "exit_code": None},
        "cleanup": {"status": "not-run", "verified": False},
    }
    lifecycle_start: dict[str, Any] = {
        "process": _not_run_process(),
        "marker_observed": False,
        "cleanup": {"status": "not-run", "verified": False},
    }
    lifecycle_passed = False
    if lifecycle_name_available:
        create_process, _ = _run_process(
            _docker_command(
                docker, docker_config,
                *_lifecycle_create_args(lifecycle_args, image),
            ),
            env=_safe_environment(docker_config), timeout=timeout,
        )
        container = _inspect_named_container(docker, docker_config, lifecycle_name)
        lifecycle_create = _stage_summary(
            create_process,
            passed=_command_ok(create_process)
            and create_process["stdout_bytes"] > 0
            and container.get("available") is True
            and container.get("owned") is True
            and container.get("status") == "created",
            container=container,
            cleanup={"status": "deferred", "verified": False},
        )
        if lifecycle_create["passed"]:
            start_process, start_sample = _run_process(
                _docker_command(docker, docker_config, "start", "-a", lifecycle_name),
                env=_safe_environment(docker_config), timeout=timeout,
            )
            lifecycle_cleanup = _cleanup_container(docker, docker_config, lifecycle_name)
            lifecycle_start = _stage_summary(
                start_process,
                passed=_command_ok(start_process)
                and start_sample == LIFECYCLE_MARKER
                and lifecycle_cleanup.get("verified") is True,
                marker_observed=start_sample == LIFECYCLE_MARKER,
                cleanup=lifecycle_cleanup,
            )
            lifecycle_passed = bool(lifecycle_start["passed"])
        else:
            lifecycle_create["cleanup"] = _cleanup_container(docker, docker_config, lifecycle_name)
    stages["container-create"] = {
        "passed": bool(lifecycle_name_available and lifecycle_create.get("passed") is True),
        "name_available": lifecycle_name_available,
        "name_check_status": name_presence["status"],
        **lifecycle_create,
    }
    stages["container-start"] = {
        "passed": lifecycle_passed,
        **lifecycle_start,
    }

    direct: dict[str, Any] = {
        "label": "direct",
        "passed": False,
        "skipped": not lifecycle_passed,
        "process": _not_run_process(),
        "response": _initialize_observation(),
        "cleanup": {"status": "not-run", "verified": False},
        "telemetry": None,
        "stderr_visibility": "bounded-in-memory",
    }
    proxy_result: dict[str, Any] = {
        "label": "proxy",
        "passed": False,
        "skipped": not lifecycle_passed,
        "process": _not_run_process(),
        "response": _initialize_observation(),
        "cleanup": {"status": "not-run", "verified": False},
        "telemetry": None,
        "stderr_visibility": "proxy-child-stderr-bounded-counters",
    }
    if lifecycle_passed:
        direct = _run_rpc_variant(
            label="direct", docker=docker, config=docker_config, proxy=None,
            docker_args=direct_args, name=direct_name, telemetry_path=None, timeout=timeout,
        )
        proxy_result = _run_rpc_variant(
            label="proxy", docker=docker, config=docker_config, proxy=proxy,
            docker_args=proxy_args, name=proxy_name, telemetry_path=telemetry_path,
            timeout=timeout,
        )
    stages["direct-exec-server-initialize"] = direct
    stages["proxy-exec-server-initialize"] = proxy_result

    direct_success = bool(direct.get("passed") is True)
    proxy_success = bool(proxy_result.get("passed") is True)
    direct_response = direct.get("response", {})
    proxy_response = proxy_result.get("response", {})
    comparison = {
        "docker_args_semantically_equal": _semantic_args(direct_args) == _semantic_args(proxy_args),
        "mount_destinations_equal": (
            _mount_destinations(direct_args)
            == _mount_destinations(proxy_args)
            == MOUNT_DESTINATIONS
        ),
        "initialize_contract": "remote-exec-server-clientName",
        "direct_initialize_success": direct_response.get("initialize_successes") == 1,
        "proxy_initialize_success": proxy_response.get("initialize_successes") == 1,
        "initialize_result_equivalent": (
            direct_response.get("initialize_successes") == proxy_response.get("initialize_successes") == 1
            and direct_response.get("initialize_error_codes") == proxy_response.get("initialize_error_codes") == {}
        ),
        "startup_equivalent": direct_success and proxy_success,
    }
    if not stages["docker-access"]["passed"]:
        failure_stage = "docker-access"
    elif not stages["image-inspect"]["passed"]:
        failure_stage = "image-inspect"
    elif not stages["container-create"]["passed"]:
        failure_stage = "container-create"
    elif not stages["container-start"]["passed"]:
        failure_stage = "container-start"
    elif not direct_success:
        failure_stage = "direct-exec-server-initialize"
    elif not proxy_success:
        failure_stage = "proxy-exec-server-initialize"
    elif not comparison["startup_equivalent"]:
        failure_stage = "direct-proxy-comparison"
    else:
        failure_stage = None
    result = {
        "schema_version": REPORT_SCHEMA_VERSION,
        "verdict": "remote-child-differential-ready" if failure_stage is None else "remote-child-differential-blocked",
        "failure_stage": failure_stage,
        "image_id": image,
        "contract": {
            "network_mode": "none",
            "include_local": False,
            "mount_destinations": list(MOUNT_DESTINATIONS),
            "candidate_env_keys": [
                "HOME", "CODEX_HOME", "PATH", "PYTHONDONTWRITEBYTECODE", "TMPDIR",
            ],
            "initialize_contract": "remote-exec-server-clientName",
            "app_server_started": False,
            "authentication_attempted": False,
            "model_execution_attempted": False,
        },
        "stages": stages,
        "comparison": comparison,
        "privacy": {
            "request_payload_preserved": False,
            "response_payload_preserved": False,
            "host_paths_preserved": False,
            "raw_stderr_preserved": False,
            "credential_files_read": False,
            "control_home_read": False,
        },
        "scope": (
            "model-free pinned Docker remote exec-server lifecycle and direct-vs-proxy "
            "initialize comparison; not App Server thread/start compatibility, authentication, "
            "model smoke, or behavioral evaluation evidence"
        ),
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--docker", type=Path, required=True)
    parser.add_argument("--docker-config", type=Path, required=True)
    parser.add_argument("--path-proxy", type=Path, required=True)
    parser.add_argument("--fixture-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--image", default=PROBE_IMAGE)
    parser.add_argument("--timeout", type=int, default=DEFAULT_TIMEOUT_SECONDS)
    args = parser.parse_args()
    try:
        result = run(
            docker=args.docker, docker_config=args.docker_config, proxy=args.path_proxy,
            fixture_root=args.fixture_root, output=args.output, image=args.image,
            timeout=args.timeout,
        )
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        print(json.dumps({
            "schema_version": REPORT_SCHEMA_VERSION,
            "verdict": "remote-child-differential-invalid-input",
            "failure_stage": "input-validation",
            "error_code": _safe_error_code(error),
            "report_written": False,
        }, ensure_ascii=False, indent=2))
        return 2
    print(json.dumps({
        "schema_version": result["schema_version"],
        "verdict": result["verdict"],
        "failure_stage": result["failure_stage"],
        "report_written": True,
    }, ensure_ascii=False, indent=2))
    return 0 if result["verdict"] == "remote-child-differential-ready" else 1


if __name__ == "__main__":
    raise SystemExit(main())
